export function copy(lang: NewsLang) {
  return COPY[lang];
}

export function fmtN(n: number, lang: NewsLang) {
  return lang === "fa" ? n.toLocaleString("fa-IR") : String(n);
}

export const CAT: Record<string, [string, string]> = {
  lab: ["Lab", "آزمایشگاه"],
  academia: ["Academia", "دانشگاه"],
  media: ["Media", "رسانه"],
  vc: ["Startups", "استارتاپ"],
  newsletter: ["Newsletter", "خبرنامه"],
  papers: ["Papers", "مقاله"],
  research: ["Research", "پژوهش"],
  product: ["Product", "محصول"],
  startup: ["Startups", "استارتاپ"],
  policy: ["Policy", "سیاست‌گذاری"],
};

export function catLabel(key: string, lang: NewsLang) {
  const row = CAT[key];
  if (!row) return key;
  return lang === "fa" ? row[1] : row[0];
}

const STATUS: Record<string, [string, string]> = {
  ok: ["OK", "موفق"],
  not_modified: ["Not modified", "بدون تغییر"],
  error: ["Error", "خطا"],
  skipped: ["Skipped", "رد شده"],
};

export function statusLabel(key: string, lang: NewsLang) {
  if (!key) return copy(lang).waiting;
  const row = STATUS[key];
  if (!row) return key;
  return lang === "fa" ? row[1] : row[0];
}
